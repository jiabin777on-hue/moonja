// Generates rapidhash test vectors from a real ninja binary.
//
//   node scripts/hash_vectors.mjs <path-to-ninja> > rapidhash_vectors_test.mbt
//
// Every command below is run once by ninja, which records the rapidhash of
// the command line in .ninja_log (format v7). The hashes therefore come from
// ninja itself, not from moonja's port. Commands cover every length branch
// of rapidhash (1-3, 4-16, 17-48, 49-95 and 96+ bytes) and non-ASCII text.

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const ninja = process.argv[2];
if (!ninja) {
  console.error('usage: node scripts/hash_vectors.mjs <path-to-ninja>');
  process.exit(2);
}

// A no-op command for the host shell, followed by a payload it ignores.
const windows = process.platform === 'win32';
const prefix = windows ? 'cmd /c rem' : ':';

// Deterministic pseudo-random payloads (xorshift32).
let state = 0x9e3779b9;
function next() {
  state ^= state << 13;
  state ^= state >>> 17;
  state ^= state << 5;
  return state >>> 0;
}
const alphabet = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-';
const unicode = ['é', 'ß', '中', '文', 'ж', '→'];

const commands = new Set();
// Short commands exist only where the shell has a short no-op (':').
if (!windows) {
  commands.add(':');
  commands.add(': ');
  commands.add(':  ');
}
for (let length = 0; length <= 300; length++) {
  let payload = '';
  for (let i = 0; i < length; i++) payload += alphabet[next() % alphabet.length];
  commands.add((prefix + ' ' + payload).trimEnd());
}
for (let i = 0; i < 40; i++) {
  let payload = '';
  const length = 1 + (next() % 120);
  for (let j = 0; j < length; j++) {
    payload += next() % 4 === 0 ? unicode[next() % unicode.length] : alphabet[next() % alphabet.length];
  }
  commands.add(prefix + ' ' + payload);
}

const dir = mkdtempSync(join(tmpdir(), 'moonja-hash-'));
try {
  const list = [...commands];
  let manifest = '';
  list.forEach((command, i) => {
    manifest += `rule r${i}\n  command = ${command}\nbuild out${i}: r${i}\n`;
  });
  writeFileSync(join(dir, 'build.ninja'), manifest);
  const run = spawnSync(ninja, ['-C', dir, '-j', '8'], { encoding: 'utf8' });
  if (run.status !== 0) {
    console.error(run.stdout, run.stderr);
    process.exit(1);
  }
  const log = readFileSync(join(dir, '.ninja_log'), 'utf8').split('\n');
  if (log[0] !== '# ninja log v7') throw new Error(`unexpected log header: ${log[0]}`);
  const hashes = new Map();
  for (const line of log.slice(1)) {
    if (!line) continue;
    const [, , , output, hash] = line.split('\t');
    hashes.set(output, hash);
  }
  const version = spawnSync(ninja, ['--version'], { encoding: 'utf8' }).stdout.trim();
  const rows = list.map((command, i) => {
    const hash = hashes.get(`out${i}`);
    if (!hash) throw new Error(`no log entry for ${command}`);
    return `    (${JSON.stringify(command)}, "${hash}"),`;
  });
  process.stdout.write(`// Generated by scripts/hash_vectors.mjs from the .ninja_log written by
// ninja ${version} on ${process.platform}. Do not edit.

///|
test "rapidhash matches the command hashes ninja writes to .ninja_log" {
  let vectors : Array[(String, String)] = [
${rows.join('\n')}
  ]
  for vector in vectors {
    let (command, expected) = vector
    assert_eq(
      @moonja.hash_command(command).to_string(radix=16),
      expected,
      msg=command,
    )
  }
}
`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
